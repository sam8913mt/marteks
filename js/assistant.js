function aiSendMsg(){
var agent=getAgent();
if(!agent){aiGate();return}
var text=String(aiInput.value||'').trim();
if(!text)return;
var r=aiThread(agent), t=r.thread, now=new Date().toISOString();
t.messages.push({role:'user',text:text,at:now});
t.updatedAt=now;t.device=agent.device||t.device||'';
t.messages.push({role:'bot',text:'',typing:true,at:now});
aiThreadStore(r.list,t);saveChats(r.list);
aiInput.value='';aiInput.style.height='auto';
aiBody.insertAdjacentHTML('beforeend',aiBubble(t.messages[t.messages.length-2])+aiBubble(t.messages[t.messages.length-1]));
aiScroll();
if(aiSuggest)aiSuggest.hidden=true;
var answer=aiAnswer(text);
cloudPost({action:'chatMessage',chatId:t.id,name:t.name,phone:t.phone||'',device:t.device||'',question:text,answer:answer});
setTimeout(function(){
var rr=aiThread(agent), th=rr.thread;
var reply={role:'bot',text:answer,at:new Date().toISOString()};
if(th.messages.length && th.messages[th.messages.length-1].typing)th.messages[th.messages.length-1]=reply;
else th.messages.push(reply);
th.updatedAt=new Date().toISOString();
aiThreadStore(rr.list,th);saveChats(rr.list);
aiBody.innerHTML=th.messages.map(aiBubble).join('');
aiScroll();
if(aiSuggest)aiSuggest.hidden=false;
},420);
}
